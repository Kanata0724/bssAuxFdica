% [解説 L1] この関数は入力を受け取り、S_lags を計算して返します。
% [意図] ファイル全体では「BSS Evalで使うフレームまたは遅延信号の行列を組み立てます。」という役割を担当します。
function S_lags=bss_make_lags(S,L);

% create a matrix containing lagged versions of some signal(s).
%
% Usage: S_lags=bss_make_lags(S,L)
%
% Input:
%   - S: n x T matrix containing the input signal(s),
%   - L: number of lagged versions of the signal(s).
%
% Output:
%   - S_lags: n*L x T matrix containing lagged versions of S, S_lags(t)=
%   [s1(t) ; s1(t-1) ; ...; s1(t-L+1); ... ; sn(t) ; sn(t-1) ; ...; sn(t-L+1)]
%
% WARNINGS:
%   * S_lags is zero-padded where necessary,
%   * We use the conventions make_lags(S,0)=makes_lags(S,1)=S.
%
% Developers:  - Cedric Fevotte (cf269@cam.ac.uk) - Emmanuel Vincent
% (vincent@ircam.fr) - Remi Gribonval (remi.gribonval@irisa.fr)

% [解説 L22] この関数の複数の計算結果を受け取り、n、T にそれぞれ保存します。
% [意図] 一つの計算で得られる関連結果を分けて保持し、後続の評価・更新・復元でそれぞれ利用するためです。
[n,T]=size(S);

% [解説 L24] 条件「L==0」を確認し、成立した場合だけ直後の処理を行います。
% [意図] 設定またはデータ状態に合った計算経路を選び、無効な処理を避けます。
if L==0
% [解説 L25] 右辺の計算結果を、後続処理で再利用できる形に保持します。結果を「処理途中で使う変数 S_lags」へ代入します。
% [意図] 時間ずれまたはフィルタ効果を含む参照部分空間を作り、許容される成分を推定信号から射影するためです。
    S_lags=S;
% [解説 L26] ここからは直前の条件が成立しなかった場合の処理で、別の設定・データ状態に対応します。
else
    
% [解説 L28] 右辺の計算結果を、後続処理で再利用できる形に保持します。結果を「処理途中で使う変数 N」へ代入します。
% [意図] 実データの軸長をループ範囲と配列shapeへ反映し、次元不一致を防ぐためです。
    N=n*L;
% [解説 L29] 後で値を書き込む配列を必要なshapeで事前確保します。結果を「処理途中で使う変数 S_lags」へ代入します。
% [意図] 時間ずれまたはフィルタ効果を含む参照部分空間を作り、許容される成分を推定信号から射影するためです。
    S_lags=zeros(N,T);
% [解説 L30] 処理途中で使う変数 i を 1:N の範囲で変えながら、同じ処理を各要素へ適用します。
% [意図] 全周波数ビンへ同じ処理を適用し、帯域の一部だけが未処理になるのを防ぐためです。
    for i=1:N
% [解説 L31] 右辺の計算結果を、後続処理で再利用できる形に保持します。結果を「観測の共分散を単位行列へ近づける白色化行列」へ代入します。
% [意図] 正解との対応付けと誤差成分分解を進め、最終的なSDR・SIR・SARへ結び付けるためです。
        q=floor((i-1)/L);
% [解説 L32] 右辺の計算結果を、後続処理で再利用できる形に保持します。結果を「AuxFDICA更新や射影に使う共分散・相関行列」へ代入します。
% [意図] 現在の音源推定に応じた統計量を作り、補助関数法の安定な分離行列更新に使うためです。
        r=mod(i-1,L);
% [解説 L33] 後で値を書き込む配列を必要なshapeで事前確保します。結果を「処理途中で使う変数 B」へ代入します。
% [意図] 正解との対応付けと誤差成分分解を進め、最終的なSDR・SIR・SARへ結び付けるためです。
        B=zeros(1,r+1); B(end)=1;
% [解説 L34] 右辺の計算結果を、後続処理で再利用できる形に保持します。結果を「処理途中で使う変数 S_lags(i,:)」へ代入します。
% [意図] 時間ずれまたはフィルタ効果を含む参照部分空間を作り、許容される成分を推定信号から射影するためです。
        S_lags(i,:)=filter(B,1,S(q+1,:));    
    end
    
end
